export function createPrototypeReadiness(): LLMReadinessResponse {
  const deployments = PROTOTYPE_MODEL_DEPLOYMENTS.map((deployment) => {
    const credentialConfigured =
      PROTOTYPE_MODEL_PROVIDERS.find((provider) => provider.provider_key === deployment.provider_key)
        ?.credential_configured ?? false;
    const blockers = credentialConfigured && deployment.status === "active" ? [] : ["credential_or_deployment_missing"];
    const warnings = deployment.config.fallback || deployment.config.fallback_group ? [] : ["fallback_not_configured"];
    const readiness = blockers.length ? "blocked" : warnings.length ? "warning" : "ready";
    return {
      blockers,
      credential_configured: credentialConfigured,
      deployment_active: deployment.status === "active",
      deployment_id: deployment.id,
      deployment_name: deployment.deployment_name,
      display_name: deployment.display_name,
      evidence: {
        mode: "prototype",
      },
      fallback_configured: warnings.length === 0,
      last_probe_message: "Prototype readiness evidence.",
      live_probe_checked_at: PROTOTYPE_NOW,
      live_probe_ok: readiness !== "blocked",
      model_key: deployment.model_key,
      policy_referenced: true,
      pricing_configured: true,
      provider_key: deployment.provider_key,
      provider_name: deployment.provider_name,
      readiness,
      routing_key: deployment.routing_key,
      warnings,
    };
  });
  return {
    deployments,
    generated_at: new Date().toISOString(),
    summary: {
      blocked: deployments.filter((item) => item.readiness === "blocked").length,
      ready: deployments.filter((item) => item.readiness === "ready").length,
      total: deployments.length,
      warning: deployments.filter((item) => item.readiness === "warning").length,
    },
  };
}

