export function createPrototypeCredentialResponse(
  providerKey: string,
  payload: {
    base_url?: string | null;
    display_name: string;
    model_key?: string | null;
    owner_id?: string | null;
    owner_type?: string;
    routing_key?: string | null;
  },
): LLMCredentialResponse {
  const secretSuffix = providerKey.slice(0, 3).padEnd(3, "x").toUpperCase();
  return {
    base_url:
      payload.base_url ??
      PROTOTYPE_MODEL_PROVIDERS.find((provider) => provider.provider_key === providerKey)?.base_url ??
      null,
    credential_configured: true,
    deployment_id:
      PROTOTYPE_MODEL_DEPLOYMENTS.find((deployment) => deployment.provider_key === providerKey)?.id ?? null,
    display_name: payload.display_name,
    masked_secret: `sk-...${secretSuffix}`,
    model_key: payload.model_key ?? null,
    owner_id: payload.owner_id ?? null,
    owner_type: payload.owner_type ?? "tenant",
    provider_key: providerKey,
    routing_key: payload.routing_key ?? null,
  };
}

